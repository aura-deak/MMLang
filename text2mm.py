def text_to_mmlang(text):
    lines = ['#0']
    for ch in text:
        lines.append(ASCII_TO_MMLANG[ch])
    lines.append('b')
    return '\n'.join(lines) + '\n'


def main():
    print('输入要打印的文本（回车结束）：')
    text = input()
    if not text:
        print('未输入文本，已退出。')
        sys.exit(0)

    source = text_to_mmlang(text)

    sanitized = re.sub(r'[^\w\u4e00-\u9fff-]+', '_', text, flags=re.UNICODE).strip('_')
    if not sanitized:
        sanitized = 'output'
    filename = sanitized + '.mmlang'

    with open(filename, 'w', encoding='utf-8') as f:
        f.write(source)

    print(f'\n已生成 MMLang 源文件：{filename}')
    print(f'字符数：{len(text)}')
    print(f'总字符 ASCII 位数：{len(text) * 8}')


if __name__ == '__main__':
    main()
